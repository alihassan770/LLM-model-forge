"""Connection pool and migration runner.

Migrations are numbered .sql files applied in order and recorded in
schema_migrations. No ORM, no autogenerated diffs - the file on disk is exactly
what runs against the database, which is what you want at 2am on a deploy.
"""

from __future__ import annotations

import logging
from pathlib import Path

from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

from .config import get_settings

log = logging.getLogger(__name__)

MIGRATIONS_DIR = Path(__file__).resolve().parent / "migrations"

_pool: ConnectionPool | None = None


def get_pool() -> ConnectionPool:
    global _pool
    if _pool is None:
        settings = get_settings()
        if not settings.database_url:
            raise RuntimeError(
                "DATABASE_URL is not set. Copy .env.example to .env and fill it in."
            )
        _pool = ConnectionPool(
            settings.database_url,
            # min_size=0 so an unreachable database does not stall start-up.
            # The web process must come up and report the problem on /healthz;
            # a process that refuses to boot tells nobody anything.
            min_size=0,
            max_size=10,
            timeout=5,
            max_idle=300,
            kwargs={"row_factory": dict_row},
            open=False,
        )
        _pool.open(wait=False)
    return _pool


def close_pool() -> None:
    global _pool
    if _pool is not None:
        _pool.close()
        _pool = None


def connection():
    """Context manager yielding a pooled connection."""
    return get_pool().connection()


def fetch_one(sql: str, params: tuple = ()) -> dict | None:
    with connection() as conn, conn.cursor() as cur:
        cur.execute(sql, params)
        return cur.fetchone()


def fetch_all(sql: str, params: tuple = ()) -> list[dict]:
    with connection() as conn, conn.cursor() as cur:
        cur.execute(sql, params)
        return cur.fetchall()


def execute(sql: str, params: tuple = ()) -> None:
    with connection() as conn, conn.cursor() as cur:
        cur.execute(sql, params)


# --------------------------------------------------------------------------- #
# Migrations
# --------------------------------------------------------------------------- #

_SCHEMA_TABLE = """
CREATE TABLE IF NOT EXISTS schema_migrations (
    version     text PRIMARY KEY,
    applied_at  timestamptz NOT NULL DEFAULT now()
)
"""


def migration_files() -> list[Path]:
    return sorted(MIGRATIONS_DIR.glob("*.sql"))


def applied_versions() -> set[str]:
    with connection() as conn, conn.cursor() as cur:
        cur.execute(_SCHEMA_TABLE)
        conn.commit()
        cur.execute("SELECT version FROM schema_migrations")
        return {r["version"] for r in cur.fetchall()}


# An arbitrary but fixed key, so every process in every replica contends for
# the same lock. Changing it would let two deploys migrate at once again.
_MIGRATION_LOCK = 8_531_207


def migrate(verbose: bool = True) -> list[str]:
    """Apply every pending migration. Returns the versions applied.

    Holds a Postgres advisory lock for the duration. On a platform that starts
    two replicas at once - which Railway does the moment you scale past one -
    both would otherwise read the same pending list and both would run it: the
    second gets a duplicate-column error and the deploy fails, on a schema
    that is actually fine. The lock makes the second wait, find nothing
    pending, and carry on.

    The lock is session-scoped, so it is released when this connection closes
    even if the process is killed mid-migration.
    """
    applied: list[str] = []

    with connection() as conn, conn.cursor() as cur:
        cur.execute("SELECT pg_advisory_lock(%s)", (_MIGRATION_LOCK,))
        conn.commit()
        try:
            # Read the applied set *inside* the lock: reading it outside is the
            # race this function exists to close.
            done = applied_versions()

            for path in migration_files():
                version = path.stem
                if version in done:
                    continue
                sql = path.read_text()
                # Each migration is its own transaction, so a failure half way
                # through leaves the database on the last good version rather
                # than between two.
                cur.execute(sql)
                cur.execute(
                    "INSERT INTO schema_migrations (version) VALUES (%s)",
                    (version,),
                )
                conn.commit()
                applied.append(version)
                if verbose:
                    print(f"  applied {version}")
        finally:
            cur.execute("SELECT pg_advisory_unlock(%s)", (_MIGRATION_LOCK,))
            conn.commit()

    if verbose and not applied:
        print("  database is up to date")
    return applied


def migration_status() -> dict:
    done = applied_versions()
    all_versions = [p.stem for p in migration_files()]
    return {
        "applied": [v for v in all_versions if v in done],
        "pending": [v for v in all_versions if v not in done],
    }
